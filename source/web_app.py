def _render(*, error: str | None = None, result: dict | None = None, status: int = 200):
    return render_template_string(PAGE, error=error, result=result), status


@app.errorhandler(413)
def request_too_large(_error):
    return _render(error="The selected files exceed the 100 MB total upload limit.", status=413)


@app.get("/")
def index():
    return _render()


@app.post("/")
def process_bills():
    uploads = [f for f in request.files.getlist("bills") if f and f.filename]
    if not uploads:
        return _render(error="Choose at least one bill image to process.", status=400)
    if len(uploads) > MAX_IMAGES:
        return _render(error=f"Upload no more than {MAX_IMAGES} bill images at a time.", status=400)

    questions = request.files.get("questions")
    if questions and questions.filename:
        if Path(questions.filename).suffix.lower() != ".csv":
            return _render(error="The optional questions file must be a .csv file.", status=400)
        questions.stream.seek(0, io.SEEK_END)
        if questions.stream.tell() > MAX_QUESTIONS_BYTES:
            return _render(error="The questions CSV must be 2 MB or smaller.", status=400)
        questions.stream.seek(0)

    run_id = uuid.uuid4().hex
    run_dir = RUNS_DIR / run_id
    inputs_dir = run_dir / "inputs"
    output_dir = run_dir / "output"
    cache_dir = run_dir / "cache"
    inputs_dir.mkdir(parents=True, exist_ok=False)
    bill_ids: set[str] = set()

    try:
        for upload in uploads:
            safe_name = secure_filename(upload.filename or "")
            suffix = Path(safe_name).suffix.lower()
            bill_id = Path(safe_name).stem
            if not safe_name or suffix not in ALLOWED_IMAGES or not bill_id:
                raise ValueError("Bill images must have a filename and use PNG, JPG, or JPEG format.")
            if bill_id in bill_ids:
                raise ValueError(f"More than one uploaded image has the bill ID {bill_id!r}. Rename one file and try again.")
            bill_ids.add(bill_id)
            target = inputs_dir / f"{bill_id}{suffix}"
            upload.save(target)
            if target.stat().st_size > MAX_IMAGE_BYTES:
                raise ValueError(f"{safe_name} exceeds the 20 MB per-image limit.")
            try:
                with Image.open(target) as image:
                    image.verify()
            except (OSError, ValueError) as exc:
                raise ValueError(f"{safe_name} is not a readable image file.") from exc

        command = [
            sys.executable, str(BASE_DIR / "main.py"), "run",
            "--bills-dir", str(inputs_dir),
            "--out-dir", str(output_dir),
            "--cache-dir", str(cache_dir),
        ]
        if questions and questions.filename:
            question_path = inputs_dir / "questions.csv"
            questions.save(question_path)
            if question_path.stat().st_size > MAX_QUESTIONS_BYTES:
                raise ValueError("The questions CSV must be 2 MB or smaller.")
            _, question_rows = cw.read_level2_template(question_path)
            unknown_ids = sorted({row["bill_id"] for row in question_rows} - bill_ids)
            if unknown_ids:
                raise ValueError("The questions CSV refers to bill IDs with no uploaded image: "
                                 + ", ".join(unknown_ids))
            command.extend(["--level2-template", str(question_path)])

        completed = subprocess.run(
            command, cwd=BASE_DIR, capture_output=True, text=True, encoding="utf-8",
            errors="replace", check=False,
        )
        log = (completed.stdout + ("\n" + completed.stderr if completed.stderr else "")).strip()
        files = []
        for filename, label in (
            ("level1.csv", "Level 1 CSV"),
            ("level2.csv", "Level 2 CSV"),
            ("run_report.json", "run report"),
        ):
            if (output_dir / filename).is_file():
                files.append((filename, label))
        report_path = output_dir / "run_report.json"
        failed_count = 0
        if report_path.is_file():
            report = json.loads(report_path.read_text(encoding="utf-8"))
            failed_count = sum(
                1 for bill in report.get("bills", {}).values()
                if bill.get("level1") != "ok"
            )
        success = completed.returncode == 0
        if success:
            message = f"Finished processing {len(bill_ids)} bill{'s' if len(bill_ids) != 1 else ''}."
        elif files:
            message = f"Processing finished with issues: {failed_count} bill(s) could not be fully extracted. "
            message += "Review the run report and processing details."
        else:
            message = "The decoder could not complete the run. Check the processing details below."
        return _render(result={
            "ok": success,
            "message": message,
            "run_id": run_id,
            "files": files,
            "log": log[-12000:],
        }, status=200 if files else 500)
    except (OSError, ValueError, csv.Error) as exc:
        shutil.rmtree(run_dir, ignore_errors=True)
        return _render(error=str(exc), status=400)
    finally:
        shutil.rmtree(inputs_dir, ignore_errors=True)
        shutil.rmtree(cache_dir, ignore_errors=True)


@app.get("/download/<run_id>/<filename>")
def download_file(run_id: str, filename: str):
    if not RUN_ID_PATTERN.fullmatch(run_id):
        abort(404)
    if filename not in {"level1.csv", "level2.csv", "run_report.json"}:
        abort(404)
    directory = RUNS_DIR / run_id / "output"
    if not (directory / filename).is_file():
        abort(404)
    return send_from_directory(directory, filename, as_attachment=True)


@app.get("/questions-template.csv")
def questions_template():
    content = io.StringIO(newline="")
    writer = csv.writer(content, lineterminator="\n")
    writer.writerow(["bill_id", "question_id", "question", "answer"])
    writer.writerow(["YOUR_IMAGE_FILENAME", "Q1", "How much of my bill is taxes?", ""])
    payload = io.BytesIO(content.getvalue().encode("utf-8"))
    return send_file(payload, mimetype="text/csv", as_attachment=True,
                     download_name="questions-template.csv")


